#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { repoRoot, rel, scanProductionAccess, workflowIdFor } from "./lib/program-inventory.mjs";
import { namedFunctionContractFor, namedFunctionDefinitionEvidenceFor, validateNamedSqlFunctionContracts } from "./lib/named-sql-function-contracts.mjs";
import { resolveWorkflowDelegation, validateWorkflowDelegations, WORKFLOW_DELEGATIONS } from "./lib/workflow-delegation-registry.mjs";

export const namedSqlFunctionInventoryPath = path.join(repoRoot, "documents/security/rls-program/generated/named-sql-function-inventory.json");
export const namedSqlFunctionInventoryReviewPath = path.join(repoRoot, "documents/security/rls-program/NAMED_SQL_FUNCTION_INVENTORY.md");

const functionName = (ts, node) => {
  for (let current = node.parent; current; current = current.parent) {
    if (ts.isFunctionDeclaration(current) && current.name) return current.name.text;
    if ((ts.isArrowFunction(current) || ts.isFunctionExpression(current)) && ts.isVariableDeclaration(current.parent)) return current.parent.name.getText();
    if (ts.isMethodDeclaration(current) && current.name) return current.name.getText();
  }
  return "module";
};

const callsInSource = ({ ts, file }) => {
  const source = fs.readFileSync(path.join(repoRoot, file), "utf8");
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const calls = [];
  const visit = (node) => {
    const rawTag = ts.isTaggedTemplateExpression(node) && ts.isPropertyAccessExpression(node.tag)
      && /\$(?:query|execute)Raw(?:Unsafe)?$/.test(node.tag.name.text);
    const rawCall = ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)
      && /\$(?:query|execute)RawUnsafe$/.test(node.expression.name.text);
    const text = rawTag ? node.template.getText(ast)
      : rawCall ? node.arguments.map((argument) => argument.getText(ast)).join(" ") : "";
    for (const match of text.matchAll(/\b(app_(?:auth|rls)\.[a-z_][a-z0-9_]*)\s*\(/gi)) {
      calls.push({
        functionName: match[1].toLowerCase(),
        sourceFile: file,
        sourceFunction: functionName(ts, node),
        line: ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1,
      });
    }
    ts.forEachChild(node, visit);
  };
  visit(ast);
  return calls;
};

const markdown = (inventory) => {
  const lines = [
    "# Named SQL function inventory",
    "",
    "Generated by `node scripts/rls/named-sql-function-inventory.mjs`. This is source evidence, not a deployable SQL package.",
    "",
    `Production calls: ${inventory.calls.length}; unique functions: ${inventory.functions.length}; reviewed contracts: ${inventory.functions.filter((item) => item.contractStatus === "reviewed").length}; missing contracts: ${inventory.functions.filter((item) => item.contractStatus !== "reviewed").length}.`,
    "",
    "| Function | Signature | Contract | Definition | Canonical workflows | Callers |",
    "|---|---|---|---|---|---|",
  ];
  for (const item of inventory.functions) lines.push(`| \`${item.functionName}\` | \`${item.signature || "missing"}\` | ${item.contractStatus} | ${item.definitionLocation || "missing"} | ${item.canonicalWorkflowIds.join("<br>") || "unresolved"} | ${item.callers.map((caller) => `${caller.sourceFile}:${caller.sourceFunction}`).join("<br>")} |`);
  lines.push("", "A production call with a missing contract is a fail-closed source-contract error. Add a checked-in definition or an explicit reviewed external migration contract with exact table-command evidence; do not add a workflow ID or edit generated manifests.", "");
  return lines.join("\n");
};

export const buildNamedSqlFunctionInventory = () => {
  const require = createRequire(import.meta.url);
  const ts = require(path.join(repoRoot, "backend/node_modules/typescript"));
  const delegations = validateWorkflowDelegations({ repoRoot });
  const scan = scanProductionAccess();
  const activeFiles = new Set(scan.activeFiles);
  const accessBySource = new Map();
  for (const access of scan.accesses) {
    const key = `${access.sourceFile}:${access.function}`;
    if (!accessBySource.has(key)) accessBySource.set(key, access);
  }
  const calls = scan.activeFiles.flatMap((file) => callsInSource({ ts, file }));
  const grouped = new Map();
  for (const call of calls) {
    if (!grouped.has(call.functionName)) grouped.set(call.functionName, []);
    grouped.get(call.functionName).push(call);
  }
  const functions = [...grouped.entries()].map(([functionName, entries]) => {
    const contract = namedFunctionContractFor(functionName);
    const definitionEvidence = namedFunctionDefinitionEvidenceFor(functionName);
    const callers = [...new Map(entries.map((entry) => [`${entry.sourceFile}:${entry.sourceFunction}:${entry.line}`, entry])).values()]
      .sort((a, b) => `${a.sourceFile}:${a.sourceFunction}:${a.line}`.localeCompare(`${b.sourceFile}:${b.sourceFunction}:${b.line}`));
    const canonicalWorkflowIds = [...new Set(callers.map((caller) => {
      const access = accessBySource.get(`${caller.sourceFile}:${caller.sourceFunction}`);
      const delegation = access ? resolveWorkflowDelegation(access, delegations)
        : WORKFLOW_DELEGATIONS.find((entry) => entry.delegated.sourceFile === caller.sourceFile && entry.delegated.function === caller.sourceFunction);
      const canonical = delegation?.canonical || (access && {
        executionSurface: access.executionSurface, sourceFile: access.sourceFile, function: access.function,
      });
      return canonical ? workflowIdFor(canonical) : null;
    }).filter(Boolean))].sort();
    return {
      functionName,
      schema: functionName.split(".")[0],
      name: functionName.split(".")[1],
      signature: contract?.signature || definitionEvidence?.signature || null,
      definitionLocation: contract?.definitionLocation || definitionEvidence?.definitionLocation || null,
      definitionKind: contract?.definitionKind || definitionEvidence?.definitionStatus || null,
      contractStatus: contract ? "reviewed" : "missing",
      security: contract?.security || null,
      tableCommands: contract?.tableCommands || [],
      requiredContext: contract?.context || null,
      canonicalWorkflowIds,
      callers,
      activeCallers: callers.map((caller) => ({ ...caller, sourceFileActive: activeFiles.has(caller.sourceFile), reachability: activeFiles.has(caller.sourceFile) ? "active-source-file" : "unregistered-source-file" })),
    };
  }).sort((a, b) => a.functionName.localeCompare(b.functionName));
  return { schemaVersion: 1, generatedFrom: ["backend/src", "scripts/rls/lib/named-sql-function-contracts.mjs"], calls: calls.sort((a, b) => `${a.sourceFile}:${a.line}:${a.functionName}`.localeCompare(`${b.sourceFile}:${b.line}:${b.functionName}`)), functions };
};

export const writeNamedSqlFunctionInventory = (inventory = buildNamedSqlFunctionInventory()) => {
  fs.writeFileSync(namedSqlFunctionInventoryPath, `${JSON.stringify(inventory, null, 2)}\n`);
  fs.writeFileSync(namedSqlFunctionInventoryReviewPath, markdown(inventory));
  return inventory;
};

export const assertNamedSqlFunctionContracts = (inventory) => {
  const missing = inventory.functions.filter((item) => item.contractStatus !== "reviewed");
  assert(!missing.length, `named SQL function contracts missing (${missing.length}): ${missing.slice(0, 6).map((item) => `${item.functionName} called by ${item.callers[0].sourceFile}:${item.callers[0].sourceFunction}`).join("; ")}. Action: add a checked-in SQL definition or reviewed external migration contract with exact table-command evidence; do not infer access from a function name.`);
  return inventory;
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const inventory = writeNamedSqlFunctionInventory();
  assertNamedSqlFunctionContracts(inventory);
  console.log(JSON.stringify({ output: rel(namedSqlFunctionInventoryPath), functions: inventory.functions.length, calls: inventory.calls.length }));
}
