#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

function usage() {
  return `Usage: node scripts/check-staging-terraform-drift-summary.mjs <summary.json>

Checks a redacted plan summary generated by scripts/plan-staging-terraform.mjs
and fails unless add=0, change=0, destroy=0. This script does not read plan
binary files, private tfvars, Terraform state, or Terraform stdout.`;
}

export function evaluateDriftSummary(summary) {
  const counts = summary?.counts || {};
  const blockers = [];
  if (summary?.status !== "plan_generated") blockers.push("summary_status_not_plan_generated");
  if (summary?.applyAllowed !== false) blockers.push("summary_apply_allowed_not_false");
  if (counts.add !== 0) blockers.push("add_count_not_zero");
  if (counts.change !== 0) blockers.push("change_count_not_zero");
  if (counts.destroy !== 0) blockers.push("destroy_count_not_zero");

  return {
    status: blockers.length === 0 ? "ok" : "blocked_drift_detected",
    terraformRoot: summary?.terraformRoot || null,
    planSummaryPath: summary?.planSummaryPath || null,
    counts: {
      add: Number.isInteger(counts.add) ? counts.add : null,
      change: Number.isInteger(counts.change) ? counts.change : null,
      destroy: Number.isInteger(counts.destroy) ? counts.destroy : null,
    },
    blockerCodes: blockers,
    rawSecretValuesPrinted: false,
    rawStatePrinted: false,
    rawPlanPrinted: false,
  };
}

export function main(argv = process.argv.slice(2)) {
  if (argv.includes("--help") || argv.includes("-h")) {
    console.log(usage());
    return 0;
  }
  if (argv.length !== 1) {
    console.log(JSON.stringify({
      status: "blocked_invalid_arguments",
      reason: "Exactly one plan summary JSON path is required.",
      rawSecretValuesPrinted: false,
      rawStatePrinted: false,
      rawPlanPrinted: false,
    }, null, 2));
    return 1;
  }

  const summaryPath = path.resolve(process.cwd(), argv[0]);
  let summary;
  try {
    summary = JSON.parse(fs.readFileSync(summaryPath, "utf8"));
  } catch {
    console.log(JSON.stringify({
      status: "blocked_invalid_summary",
      reason: "Plan summary JSON is missing or invalid.",
      rawSecretValuesPrinted: false,
      rawStatePrinted: false,
      rawPlanPrinted: false,
    }, null, 2));
    return 1;
  }

  const result = evaluateDriftSummary(summary);
  console.log(JSON.stringify(result, null, 2));
  return result.status === "ok" ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main());
}
